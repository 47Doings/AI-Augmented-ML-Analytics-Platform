"""Database access.

Each workspace (business) has its own PostgreSQL schema, e.g. ws_demo or
ws_3fa91c07d2b4e655. Two rules keep that safe:

1. Schema names are generated by the server (make_schema_name), never built
   from anything a user typed, such as the business name.
2. Every schema name is validated against a strict pattern and then quoted
   with sql.Identifier before it goes into a query.
"""
import logging
import re
import secrets

import psycopg
from psycopg import sql

from core.config import get_settings

logger = logging.getLogger(__name__)

# 'ws_' followed by 1-50 lowercase letters, digits or underscores. Nothing else.
_SCHEMA_RE = re.compile(r"^ws_[a-z0-9_]{1,50}$")


def validate_schema_name(name: str) -> str:
    if not isinstance(name, str) or not _SCHEMA_RE.fullmatch(name):
        raise ValueError(f"Invalid workspace schema name: {name!r}")
    return name


def make_schema_name() -> str:
    """A new, unguessable schema name for a new workspace."""
    return "ws_" + secrets.token_hex(8)


def connect(schema: str | None = None) -> psycopg.Connection:
    """Open a connection. If a schema is given, queries run inside that workspace.

    Use it as a context manager so the connection is always closed:
        with connect("ws_demo") as conn:
            ...
    """
    settings = get_settings()
    conn = psycopg.connect(
        host=settings.postgres_host,
        port=settings.postgres_port,
        user=settings.postgres_user,
        password=settings.postgres_password.get_secret_value(),
        dbname=settings.postgres_db,
        connect_timeout=5,
    )
    if schema is not None:
        validate_schema_name(schema)
        with conn.cursor() as cur:
            cur.execute(sql.SQL("SET search_path TO {}").format(sql.Identifier(schema)))
        conn.commit()
        logger.debug("Connected with search_path=%s", schema)
    return conn
